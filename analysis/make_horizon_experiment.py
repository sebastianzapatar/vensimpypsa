"""Build the inputs of experiment H1 (fixed planning horizon).

Writes, from the existing files and without changing them:

* analysis/config/scenarios_horizon.csv -- the eight scenarios of
  config/scenarios.csv, each run twice: with the long horizon forced
  (suffix _H7, Planning Horizon Mode = 1) and with the short horizon forced
  (suffix _H1, Planning Horizon Mode = 2). The mode is the cell
  'General Parameters'!B31 read by the *_H models (add_horizon_switch.py).
* analysis/config/{brazil,chile}_horizon.json -- the country configurations,
  pointing at the *_H.vpmx models and saving the extra outputs needed for
  Table 3 and for checking which horizon each run used.

Run from the repository root:
    python analysis/make_horizon_experiment.py
"""

from __future__ import annotations

import csv
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
CONFIG = HERE / "config"

MODES = [("H7", 1, "long horizon forced: generation f7, transmission f7"),
         ("H1", 2, "short horizon forced: generation f1, transmission f0")]

EXTRA_OUTPUTS = [
    "Monthly Mean Generation Price[f0]",
    "Mean Availability Margin",
    "Min Availability Margin",
    "Use Long Generation Horizon",
    "Use Short Transmission Horizon",
]

MODEL = {"brazil": "../../modelo/brasil/ModeloBR_H.vpmx",
         "chile": "../../modelo/chile/ModeloCL_H.vpmx"}


def build_scenarios() -> int:
    source = CONFIG / "scenarios.csv"
    rows = []
    with source.open(newline="", encoding="utf-8-sig") as stream:
        for row in csv.DictReader(stream):
            if not row.get("scenario") or row["scenario"].lstrip().startswith("#"):
                continue
            rows.append(row)
    scenarios = list(dict.fromkeys(r["scenario"] for r in rows))

    target = CONFIG / "scenarios_horizon.csv"
    with target.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=["scenario", "country", "sheet",
                                                    "ref", "value", "note"])
        writer.writeheader()
        # Comment rows go after the header, as in scenarios.csv; no commas
        # inside them, so each is read as a single 'scenario' field.
        stream.write(
            "# Experiment H1 (Energy review R1.4): the scenarios of scenarios.csv\n"
            "# run with the planning horizon forced. Generated by\n"
            "# make_horizon_experiment.py - edit that script and not this file.\n"
            "# _H7 must reproduce the published S0-S7 (the reference rule uses f7)\n"
            "# and _H1 is the short-horizon counterfactual.\n"
        )
        count = 0
        for suffix, mode, note in MODES:
            for scenario in scenarios:
                name = f"{scenario}_{suffix}"
                for row in rows:
                    if row["scenario"] == scenario:
                        writer.writerow({**{k: row.get(k, "") for k in writer.fieldnames},
                                         "scenario": name})
                writer.writerow({"scenario": name, "country": "",
                                 "sheet": "General Parameters", "ref": "B31",
                                 "value": mode, "note": note})
                count += 1
    print(f"wrote {target.name}: {count} scenarios per country")
    return count


def build_configs() -> None:
    for country in ("brazil", "chile"):
        config = json.loads((CONFIG / f"{country}.json").read_text(encoding="utf-8"))
        config["experiment"] = "H1 - fixed planning horizon (review R1.4)"
        config["model"] = MODEL[country]
        for key in ("outputs", "savelist"):
            config[key] = list(dict.fromkeys(config[key] + EXTRA_OUTPUTS))
        target = CONFIG / f"{country}_horizon.json"
        target.write_text(json.dumps(config, indent=2, ensure_ascii=False) + "\n",
                          encoding="utf-8")
        print(f"wrote {target.name}")


if __name__ == "__main__":
    build_scenarios()
    build_configs()
